export function getStrings(): { t: Strings; rtl: boolean } {
  const lang = (document.documentElement.lang || navigator.language || 'en').toLowerCase();
  const isAr = lang.startsWith('ar');
  return { t: isAr ? ar : en, rtl: isAr };
}

